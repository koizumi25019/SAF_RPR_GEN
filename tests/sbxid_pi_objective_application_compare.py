"""Compare s5378 limit30 runs using both PI objectives, sequentially.

--fault-samples selects evenly spaced detecting faults from the lab reference;
omit it to run all representatives generated by the application.
"""
import argparse
import csv
from decimal import Decimal
import json
import os
from pathlib import Path
import re
import subprocess


def run(args):
    root = Path(__file__).resolve().parents[1]
    output = args.output.resolve()
    output.mkdir(parents=True, exist_ok=True)
    env = dict(os.environ, FDP_NORMAL_SCOPE_VALIDATE="1", FDP_SBXID_VERIFY="1")
    fault_option = ""
    if args.fault_samples:
        reference = root / "SB-XID/tp/1f1p/s5378_C_1f1p_fault.txt"
        faults = reference.read_text().splitlines()
        assert 2 <= args.fault_samples <= len(faults)
        selected = [faults[k * (len(faults) - 1) // (args.fault_samples - 1)]
                    for k in range(args.fault_samples)]
        fault_path = output / "faults.txt"
        fault_path.write_text("\n".join(selected) + "\n")
        fault_option = f"-fault {fault_path}\n"
    results, records = {}, {}
    for mode in ("all", "scope"):
        prefix = output / mode
        config = prefix.with_suffix(".set")
        config.write_text(
            "-net input/circuit/saf/s5378_C.v\n"
            + fault_option +
            f"-fdp {prefix.with_suffix('.csv')}\n"
            f"-log {prefix.with_suffix('.log')}\n"
            f"-limit 30\n-jobs {args.jobs}\n-dom_reuse off\n"
            f"-sbxid_pi_objective {mode}\n")
        with prefix.with_suffix(".stdout").open("w") as stdout, \
                prefix.with_suffix(".stderr").open("w") as stderr:
            subprocess.run([str(args.binary.resolve()), "-set", str(config)],
                           cwd=root, env=env, stdout=stdout, stderr=stderr,
                           check=True, timeout=args.timeout)
        log = prefix.with_suffix(".log").read_text()

        def field(name):
            match = re.search(r"//\s+" + re.escape(name) + r"\s+:\s+([^\n]+)", log)
            assert match, name
            return match[1]

        verified, failed = map(int, field("SB-XID Verified / Failed").split(" / "))
        assert failed == 0
        optimal, feasible = map(int, field("Clasp Optimal / Feasible").split(" / "))
        timeouts, unknown = map(int, field("Clasp Timeouts / UNKNOWN Fallbacks").split(" / "))
        with prefix.with_suffix(".csv").open() as stream:
            rows = list(csv.DictReader(stream))
        # WriteEquivFaults writes equivalent faults with empty complete. The
        # representatives are complete=1 or 0, and have their own cube counts.
        representatives = [r for r in rows if r["complete"] in ("0", "1")]
        records[mode] = {(r["net_name"], r["f_type"]): r for r in rows}
        results[mode] = dict(
            wall_seconds=float(field("Time").split()[0]),
            cpu_seconds=float(field("CPU Time").split()[0]),
            cadical_cpu_seconds=float(field("CPU Time (CaDiCaL)").split()[0]),
            sbxid_cpu_seconds=float(field("CPU Time (Don't care)").split()[0]),
            clasp_search_seconds_sum=float(field("Clasp Search Wall Time (sum of calls)").split()[0]),
            optimal=optimal, feasible=feasible, timeouts=timeouts, unknown=unknown,
            verified=verified, verification_failures=failed,
            fault_rows=len(rows), representatives=len(representatives),
            complete=sum(r["complete"] == "1" for r in representatives),
            incomplete=sum(r["complete"] == "0" for r in representatives),
            total_cubes=sum(int(r["cube_cnt"]) for r in representatives),
        )
        print(mode, json.dumps(results[mode]), flush=True)
    a, b = records["all"], records["scope"]
    assert a.keys() == b.keys()
    shared = [k for k in a if a[k]["complete"] == b[k]["complete"] == "1"]
    assert all(Decimal(a[k]["fdp"]) == Decimal(b[k]["fdp"]) for k in shared)
    reps = [k for k in a if a[k]["complete"] in ("0", "1")]
    assert all(b[k]["complete"] in ("0", "1") for k in reps)
    quality = dict(
        common_complete=len(shared), common_complete_fdp_mismatches=0,
        complete_to_incomplete=sum(a[k]["complete"] == "1" and b[k]["complete"] == "0" for k in reps),
        incomplete_to_complete=sum(a[k]["complete"] == "0" and b[k]["complete"] == "1" for k in reps),
        scope_fdp_higher=sum(Decimal(b[k]["fdp"]) > Decimal(a[k]["fdp"]) for k in reps),
        equal_fdp=sum(Decimal(b[k]["fdp"]) == Decimal(a[k]["fdp"]) for k in reps),
        all_fdp_higher=sum(Decimal(b[k]["fdp"]) < Decimal(a[k]["fdp"]) for k in reps),
    )
    report = dict(circuit="s5378_C", cube_limit=30, jobs=args.jobs,
                  selected_faults=args.fault_samples or "all representatives",
                  fault_selection="evenly spaced rows of lab reference" if args.fault_samples else "all",
                  dominance_reuse=False, trials=1, order=["all", "scope"],
                  post_solve_verification=True, normal_scope_validation=True,
                  **results, quality=quality,
                  caveat="Incomplete FDP values are lower bounds; covers and seed sequences may differ.")
    (output / "summary.json").write_text(json.dumps(report, indent=2) + "\n")
    print(json.dumps(report, indent=2))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--binary", type=Path, required=True)
    parser.add_argument("--output", type=Path, required=True)
    parser.add_argument("--jobs", type=int, default=2)
    parser.add_argument("--timeout", type=int, default=3600)
    parser.add_argument("--fault-samples", type=int, default=0)
    run(parser.parse_args())
