//-------------------------------------------------------------------------------------------------------------
//	cube_trend.c : テストキューブ列の構造傾向を観察する検証ツール（env CUBE_TREND=1）
//
//	1故障について UNSAT まで（または -limit まで）列挙したキューブ列を後から走査し、
//	「キューブ生成回数が爆発する故障」の原因仮説を検証する：
//	  (1) Xの数が極端に少なくなる        → x_count / X率 と列挙先頭→末尾での推移
//	  (2) Xの箇所がほとんど一緒（拡大効果がほぼない）
//	                                     → Xマスクの重複率・X出現位置の集中度・
//	                                       連続キューブ間のマスク一致/値差分
//	終了時に [CT] バケット集計を出し、キューブ数の多い故障ほど X が少ない/マスクが
//	使い回されているか（=仮説の真偽）を直接示す。
//
//	env:
//	  CUBE_TREND=1        有効化。故障ごとに [CT] 1行サマリ、終了時にバケット集計。
//	  CUBE_TREND_CSV=path 故障×キューブの明細を CSV 追記（プロット用）。
//	  CUBE_TREND_DUMP=名  その名前を含む故障の生成キューブ('0'/'1'/'X'列)を
//	  CUBE_TREND_DUMPFILE=path へ書き出す（ビット列の具体例・作図用）。
//	注: 支配流用が有効だと cubes 先頭に subset_faults の種キューブが入り生成順が
//	    濁る。単一故障の純粋な生成順を見たいときは MDC_NODOM=1 を併用する。
//	検証記録: verification/cube_trend/SUMMARY.md
//-------------------------------------------------------------------------------------------------------------
