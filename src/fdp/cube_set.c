#include <stdlib.h>

#include "./cube_set.h"

#define CUBESET_MIN_CAP 8

//*************************************************************************************************************
//	@name		cubeset_init
//	@function	キューブ集合を初期化する
//*************************************************************************************************************
void cubeset_init(CubeSet* cs, int cap)
{
	if (cap <= 0) cap = CUBESET_MIN_CAP;
	cs->data = (char**)malloc((size_t)cap * sizeof(char*));
	cs->n    = 0;
	cs->cap  = cap;
}

//*************************************************************************************************************
//	@name		cubeset_push
//	@function	キューブを末尾に追加する（必要なら容量を倍に拡張）
//*************************************************************************************************************
void cubeset_push(CubeSet* cs, char* cube)
{
	if (cs->n == cs->cap)
	{
		cs->cap  = (cs->cap > 0) ? cs->cap * 2 : CUBESET_MIN_CAP;
		cs->data = (char**)realloc(cs->data, (size_t)cs->cap * sizeof(char*));
	}
	cs->data[cs->n++] = cube;
}

//*************************************************************************************************************
//	@name		cubeset_free
//	@function	全キューブと内部配列を解放し、空状態に戻す
//*************************************************************************************************************
void cubeset_free(CubeSet* cs)
{
	for (int i = 0; i < cs->n; i++)
		free(cs->data[i]);
	free(cs->data);
	cs->data = NULL;
	cs->n    = 0;
	cs->cap  = 0;
}
