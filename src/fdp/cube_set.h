#pragma once
//-------------------------------------------------------------------------------------------------------------
//	CubeSet : テストキューブ集合を所有する可変長コンテナ
//	  各キューブは '0'/'1'/'X' を n_pi 文字並べた '\0' 終端文字列。
//	  追加した char* の所有権は CubeSet が持ち、cubeset_free でまとめて解放する。
//-------------------------------------------------------------------------------------------------------------
typedef struct CubeSet
{
	char** data;   /**< キューブ文字列の配列 */
	int    n;      /**< 格納しているキューブ数 */
	int    cap;    /**< data の確保済み容量 */
}
CubeSet;

/** cap 本ぶんの容量で初期化する（cap<=0 なら既定値を使う） */
void cubeset_init(CubeSet* cs, int cap);

/** キューブ 1 本を末尾に追加する（cube の所有権を受け取る） */
void cubeset_push(CubeSet* cs, char* cube);

/** 全キューブと内部配列を解放し、空状態に戻す */
void cubeset_free(CubeSet* cs);
