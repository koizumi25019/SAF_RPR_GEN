/** 故障読み込み・レベル計算後に一度だけ選択順を作る。レベル昇順、同レベルでは故障表の走査順。 */
bool InitTargetOrder(void);

/** 選択用配列だけを解放する。故障ノードは解放しない。 */
void FreeTargetOrder(void);

/** InitTargetOrder後、全対象故障を同じ順で複製した配列を返す。
 *  配列だけを呼出側がfreeする。故障ノード本体の所有権は移さない。失敗はNULL。 */
FNODE** CopyTargetOrder(int* count);
