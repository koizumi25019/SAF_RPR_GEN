//  戻り値 : なし
//  引  数 : ファイルポインタ
//----------------------------------------------
void	file_output_double_dtection_tp(FILE* fp){

	int		i,j;
	int		n_ddtp=0;
//	FILE	*log;


	//==========================================
	// 二重検出後のテストパターン出力
	//==========================================
	for(i=0; i<n_tp; i++){
		//選択されたTPのみ出力
		if(dd_tbl[i].select == YES){
			
			//二重検出後のテストパターン数
			n_ddtp++;
			
			//出力
			for(j=0; j<n_pi; j++){
				//----------------------------------------
				if( (Get_NBit(pi_tp[j].tp,i)) == 0){
					fprintf(fp, "0");
				}
				//----------------------------------------
				else if( (Get_NBit(pi_tp[j].tp,i)) == 1){
					fprintf(fp, "1");
				}
				//----------------------------------------
				else if( (Get_NBit(pi_tp[j].tp,i)) == 3){
					fprintf(fp, "X");
				}
				//----------------------------------------
			}
			fprintf(fp, "\n");
		}
	}
	

	//==========================================
	// 二重検出後のテストパターン数ログ
	//==========================================
}