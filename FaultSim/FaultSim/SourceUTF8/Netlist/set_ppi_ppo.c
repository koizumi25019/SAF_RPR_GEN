//  機  能 : PPIとPPOポインタ配列の作成
//  戻り値 : なし
//  引  数 : なし
//----------------------------------------------
void	set_ppi_ppo(){

	int		i;

	//===========================================================
	// PPIポインタ配列作成 (※PPI=DFF)
	//===========================================================
	//------------------------------------
	// メモリ確保
	//------------------------------------
	n_ppi = n_sdff;
	ppi = (S_NLIST**)malloc(sizeof(S_NLIST*) * n_ppi);
	
	//------------------------------------
	// ポインタ接続
	//------------------------------------
	for(i=0; i<n_ppi; i++){
		ppi[i] = sdff[i];
	}


	//===========================================================
	// PPOポインタ配列作成 (※PPO≠DFF)
	//===========================================================
	//------------------------------------
	// メモリ確保
	//------------------------------------
	n_ppo = n_sdff;
	ppo = (S_NLIST**)malloc(sizeof(S_NLIST*) * n_ppo);
	
	//------------------------------------
	// ポインタ接続
	//------------------------------------
	for(i=0; i<n_ppo; i++){
		ppo[i] = sdff[i]->in[0];	//※DFFの入力信号線がPPOになる
	}

#ifdef DEBUG
	printf("\n//-----------------------------------------\n");
	printf("// DEBUG: PPIポインタとPPOポインタ確認\n");
	printf("//-----------------------------------------\n");
	for(i=0; i<n_ppi; i++)printf("PPI[%d]: %s (%s)\n", i, ppi[i]->name, ppi[i]->name_ins);
	printf("\n");
	for(i=0; i<n_ppo; i++)printf("PPO[%d]: %s\n", i, ppo[i]->name);
	printf("\n");
#endif

}