//----------------------------------------------
//  関数名 : sppfp_lsim_3v_xid_exor
//  機  能 : EXOR論理演算(組合せ回路)
//  戻り値 : 演算対象信号線
//  引  数 : なし
// ※2入力EXORのみ対応！
//----------------------------------------------
static void sppfp_lsim_3v_xid_exor(NLIST *net){
	
	//-----------------------------------------
	// X^X と 1^X の演算のみ例外処理
	//-----------------------------------------
	if( (net->in[0]->one_tp_nval+net->in[1]->one_tp_nval) >= 4){
		net->one_tp_nval = 3;	//例外演算：出力値はドントケア
	}
	//-----------------------------------------
	// その他は通常演算
	//-----------------------------------------
	else{
		net->one_tp_nval = net->in[0]->one_tp_nval ^ net->in[1]->one_tp_nval;
	}


}//END


