//----------------------------------------------
//  関数名 : SAF_3v_XID_SPPFP_LSIM
//  機  能 : X抽出後テストパターンで3値論理シミュレーション(X抽出専用)
//  戻り値 : なし
//  引  数 : tp_id(SPPFPの対象となるTP番号)
//  【未使用関数】
//----------------------------------------------
void	SAF_3v_XID_SPPFP_LSIM(int tp_id){

	int i,j;


	//================================================
	// 関数ポインタ設定
	//================================================
	static void(*func[20])(NLIST*);
	func[FOUT]	= sppfp_lsim_3v_xid_fout;
	func[BUF]	= sppfp_lsim_3v_xid_buf;
	func[INV]	= sppfp_lsim_3v_xid_inv;
	func[AND]	= sppfp_lsim_3v_xid_and;
	func[NAND]	= sppfp_lsim_3v_xid_nand;
	func[OR]	= sppfp_lsim_3v_xid_or;
	func[NOR]	= sppfp_lsim_3v_xid_nor;
	func[EXOR]	= sppfp_lsim_3v_xid_exor;
	func[EXNOR]	= sppfp_lsim_3v_xid_exnor;
	
	
	//================================================
	// X抽出後のテストパターンを印加
	//================================================
	for(i=0; i<n_pi; i++){

		//----------------------------------------
		//対象TPの対象PIがドントケアじゃない場合場合
		//----------------------------------------
		if(Get_NBit(pi[i]->xid_nval, tp_id) != 3){
			pi[i]->one_tp_nval = (int)Get_NBit(pi[i]->nval, tp_id);		//対象TPの対象PIの正常値{0 or 1}を直接代入
		}
		
		//----------------------------------------
		//ドントケアの場合
		//----------------------------------------
		else{
			pi[i]->one_tp_nval = 3;	//ドントケア:3 を代入
		}
	}

	
	//================================================
	// 論理シミュレーション
	//================================================
	fprintf(stderr,"\n SAF_3v_XID_SPPFP_LSIM\n");
	fprintf(stderr,"|----+----|----+----|----+----|----+----|----+----|\n");

	for(i=1; i<max_level+1; i++){
		// Progress Bar
		if(((int)i % (int)(((max_level)*2/100)+1)) == 0)fprintf(stderr,"*");

		//論理SIM
		for(j=0; j<nml_lev[i].n_net; j++){
			(*func[nml_lev[i].net[j]->type])(nml_lev[i].net[j]);
		}
	}

	

}//END
