//----------------------------------------------
//  関数名 : sppfp_lsim_3v_xid_fout
//  機  能 : FOUT論理演算(組合せ回路)
//  戻り値 : 演算対象信号線
//  引  数 : なし
//----------------------------------------------
static void sppfp_lsim_3v_xid_fout(NLIST *net){
	
	//stemの正常値をそのまま代入
	net->one_tp_nval = net->in[0]->one_tp_nval;
}

//----------------------------------------------
//  関数名 : sppfp_lsim_3v_xid_buf
//  機  能 : BUF論理演算(組合せ回路)
//  戻り値 : 演算対象信号線
//  引  数 : なし
//----------------------------------------------
static void sppfp_lsim_3v_xid_buf(NLIST *net){
	
	//入力[0]の正常値をそのまま代入
	net->one_tp_nval= net->in[0]->one_tp_nval;
}

//----------------net->one_tp_nval------------------------------
//  関数名 : sppfp_lsim_3v_xid_inv
//  機  能 : INV論理演算(組合せ回路)
//  戻り値 : 演算対象信号線
//  引  数 : なし
//----------------------------------------------
static void sppfp_lsim_3v_xid_inv(NLIST *net){
	
	//----------------------------------
	// 入力[0]の正常値0
	//----------------------------------
	if(net->in[0]->one_tp_nval == 0){
		net->one_tp_nval = 1;	//反転値1を代入
	}
	//----------------------------------
	// 入力[0]の正常値1
	//----------------------------------
	else if(net->one_tp_nval == 1){
		net->one_tp_nval = 0;	//反転値0を代入
	}
	//----------------------------------
	// 入力[0]の正常値X
	//----------------------------------
	else if(net->one_tp_nval == 3){
		net->one_tp_nval = 3;	//ドントケアのまま
	}
}

//----------------------------------------------
//  関数名 : sppfp_lsim_3v_xid_and
//  機  能 : AND論理演算(組合せ回路)
//  戻り値 : 演算対象信号線
//  引  数 : なし
//----------------------------------------------
static void sppfp_lsim_3v_xid_and(NLIST *net){
	
	int		i;
	
	//===========================================
	//初期値代入 (in[0]の値)
	//===========================================
	net->one_tp_nval = net->in[0]->one_tp_nval;
	
	//===========================================
	//in[0]が制御値(0)以外の場合計算
	//===========================================
	if(net->one_tp_nval != 0){
		//入力線数分演算
		for(i=1; i<net->n_in; i++){
			//----------------------------------------
			// 現在値と入力値が1とXの組合せ
			//----------------------------------------
			if( (net->one_tp_nval+net->in[i]->one_tp_nval) == 4 ){	//非制御値(1)とドントケア(3)
				net->one_tp_nval |= net->in[i]->one_tp_nval;		//例外処理
			}
			//----------------------------------------
			// その他の組合せ
			//----------------------------------------
			else{
				net->one_tp_nval &= net->in[i]->one_tp_nval;		//通常演算
			}
		}
	}
}

