//------------------------------------------------------------
// 関数名 : trans_ffc_list
// 機能   : FFCファイルの変換
// 戻り値 : なし
// 引数   : fp(入力FFCファイルポインタ), in_name(入力FFCファイル名)
//
//【入力ファイルフォーマット】
// FFC名
// FFC名
// FFC名
//
//■実行コマンド例■
//-c s5378_tpi.v -cpixid YES -fm TDF -st s5378_cc.stil -trans_ffc s5378_greedy_no1.txt
//(CPI回路，初期回路のテスト集合.stil，変換したいFFCリスト)
//------------------------------------------------------------
void trans_ffc_list(FILE *fp, char *in_name){

	int		i;
	int		count=0;
	char	str[MAXN];
	char	*net;
	int		*ffc_id;
	int		n_ffc_list = 0;
	FILE	*tfp;				//変換先ファイルポインタ
	char	fname[1000];		//変換ファイル名

	//=====================================================
	//FFC数をカウント
	//=====================================================
	//行数計算
	while(fgets(str,MAXN,fp)!=NULL)n_ffc_list++;
	
	//ファイルポインタ戻す
	rewind(fp);

	
	//=====================================================
	//FFC_ID保存配列をメモリ確保
	//=====================================================
	ffc_id = (int*)malloc(sizeof(int) * n_ffc_list);


	//=====================================================
	//FFCインスタンス名とオリジナルFF名を格納
	//=====================================================
	while(fgets(str,MAXN,fp)!=NULL){
		
		//------------------------------------
		//FFCインスタンス名切り出し
		//------------------------------------
		net = strtok(str,"\n");

		//------------------------------------
		//FFC探索
		//------------------------------------
		for(i=0; i<n_ffc; i++){
			if(strcmp(net, ffc[i]->name_ins) == 0){
				ffc_id[count] = i;
				count++;
				break;
			}
		}		
	}
	
	//=====================================================
	// 変換ファイルを出力
	//=====================================================	
	//---------------------------------------------
	// 出力ファイル名作成
	//---------------------------------------------
	strcpy(fname, "trans_");
	strcat(fname, in_name);
	
	//---------------------------------------------
	// ファイルオープン
	//---------------------------------------------
	tfp = fopen(fname, "w");

	//---------------------------------------------
	// ファイル出力
	//---------------------------------------------
	for(i=0; i<count; i++){
		//FFC名　オリジナルFF名　の順に出力
		fprintf(tfp, "%s %s\n", ffc[ffc_id[i]]->name_ins, ffc[ffc_id[i]]->link_cpi[0]->name);
	}
	
	//---------------------------------------------
	// ファイルクローズ
	//---------------------------------------------
	fclose(tfp);


	//終了
	exit(2);

}