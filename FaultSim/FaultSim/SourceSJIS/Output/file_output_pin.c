//機能　：PIN情報をファイル出力
//引数　：fp(出力ファイルポインタ)
//戻り値：なし
//--------------------------------------------------------------------
void file_output_pin(FILE* fp){

	int		i;

	//======================================================
	// 縮退故障モデル
	//======================================================
	if(opt.fmodel == SAF){
		for(i=0; i<n_pi; i++){
			fprintf(fp, "%s\n", pi[i]->name);
		}
	}
	
	//======================================================
	// 遷移故障モデル
	//======================================================
	if(opt.fmodel == TDF){
		
		//PI
		for(i=0; i<n_spi; i++){
			fprintf(fp, "%s\n", spi[i]->name);
		}

		//PPI
		for(i=0; i<n_ppi; i++){
			fprintf(fp, "%s\n", ppi[i]->name);
		}
	}
	
	
}