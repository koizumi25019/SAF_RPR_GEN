//----------------------------------------------
//  関数名 : sort_cpi_tp
//  機  能 : 【遷移故障】制御ポイント挿入箇所範囲内故障数の降順でテストパターンをソート
//  戻り値 : なし
//  引  数 : なし
//----------------------------------------------
void	sort_cpi_tp(){

	int			i;


	//========================================================
	// テストパターン情報のアドレス代入
	//========================================================
	for(i=0; i<n_tp ;i++){
		sort_tp[i] = &tp_info[i];
	}

	
	//========================================================
	// 制御ポイント挿入範囲内故障数の降順ソート
	//========================================================
	qsort((void*)sort_tp, n_tp, sizeof(TPINFO*), comp_cpi_tp);

	
	//========================================================
	// DEBUG
	//========================================================
#ifdef DEBUG
	for(i=0; i<n_tp ;i++){
		printf("tp[%d] %d\n", sort_tp[i]->tp_id, sort_tp[i]->n_cpi_fault);
	}
	printf("\n");
#endif

}

//----------------------------------------------
//  関数名 : comp_cpi_tp
//  機  能 : qsort用の比較関数
//  戻り値 : 比較結果
//  引  数 : 要素1, 要素2
//----------------------------------------------
int	comp_cpi_tp(const void  *c0, const void  *c1){
	return( (*((TPINFO **)c1))->n_cpi_fault - (*((TPINFO **)c0))->n_cpi_fault );
}