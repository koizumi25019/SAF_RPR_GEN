//----------------------------------------------
//  関数名 : make_fsim_det_num
//  機  能 : 故障シミュレーションで検出した故障数を調査(1故障1検出：対象故障のみ)
//  戻り値 : なし
//  引  数 : なし
//----------------------------------------------
void	make_fsim_det_num(){

	int	i;

	//================================================
	// 初期化
	//================================================
	n_detect = 0;

	//================================================
	// 縮退故障の場合(故障フラグYESのやつのみ出力)
	//================================================
	if(opt.fmodel == SAF){

		for(i=0; i<n_net; i++){

			//-------------------------------------
			// 0縮退故障
			//-------------------------------------
			if(nl[i].test_sf0==YES && nl[i].det_sf0>0){
				n_detect++;
			}
		
			//-------------------------------------
			// 1縮退故障
			//-------------------------------------
			if(nl[i].test_sf1==YES && nl[i].det_sf1>0){
				n_detect++;
			}
		}

	}
	
	//================================================
	// 遷移故障の場合
	//================================================
	else if(opt.fmodel == TDF){
		for(i=0; i<n_snet; i++){

			//-------------------------------------
			// 立上り遷移故障
			//-------------------------------------
			if(s_nl[i].test_str==YES && s_nl[i].det_str>0){
			//if(s_nl[i].det_str>0){
				n_detect++;
			}
		
			//-------------------------------------
			// 立下り遷移故障
			//-------------------------------------
			if(s_nl[i].test_stf==YES && s_nl[i].det_stf>0){
			//if(s_nl[i].det_stf>0){
				n_detect++;
			}
		}

	}

}