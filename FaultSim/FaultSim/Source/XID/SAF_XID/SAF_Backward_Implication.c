		//********************************************************************
		case EXOR:
		case EXNOR:
			//-----------------------------------------------------------
			// 出力=1 (※制御値が無いため2入力とも遡る(後方含意))
			//-----------------------------------------------------------
			//       ＿＿＿                     ＿＿＿
			//   1 --＼    ＼               0 --＼    ＼
			//         ))EXOR>--- 1               ))EXOR>--- 1
			//   0 --／    ／               1 --／    ／
