			//-----------------------------------------------------------
			// 出力=1 (※制御値が無いため2入力とも遡る(後方含意))
			//-----------------------------------------------------------
			//       ＿＿＿                     ＿＿＿
			//   0 --＼    ＼               1 --＼    ＼
