//----------------------------------------------
//  関数名 : TDF_2v_distribution_ppsfp
//  機  能 : STEMからの2値遷移故障PPSFPイベントドリブン
//  戻り値 : なし
//  引  数 : tp_id(テストパターン番号配列), tp_count(テストパターン数), fnet(故障信号線), ed_flag(計算済みフラグ値)
//----------------------------------------------
void	TDF_2v_distribution_ppsfp(int *tp_id, int tp_count, SXID_LIST* fnet, unsigned int ed_flag){

	int				i;
	int				level_flag=0;		//event_lev更新時にbreakしないようにする
	int				event_lev;			//イベント計算するレベル(※計算しながら更新)
	S_NLIST			*temp_net;			//レベライズスタックから取り出した信号線を一時的に格納
//	unsigned int	det_tp_list=0;		//PPOまで故障伝搬したTPリスト【0:未伝搬 1:伝搬(=故障検出)】	//未使用のため削除
	unsigned int	exor_ppo;			//正常値と故障値のEXOR結果(故障伝搬テストパターンは1が立つ)
	
	//=========================================================
	// 故障信号線の初期化
	//=========================================================
	//故障フラグの設定
	fnet->net->flag = ed_flag;
	
	//故障値設定
	fnet->net->x_fault = fnet->net->dis_nval_t2->p_buf[0];		//x_faulにp_bufを代入(反転)
	fnet->net->p_fault = fnet->net->dis_nval_t2->x_buf[0];		//p_faulにx_bufを代入(反転)


	//=========================================================
	// 故障信号線の次イベントをレベライズスタックへプッシュ
	//=========================================================
	TDF_EDpush(fnet->net, ed_flag);


	//=========================================================
	// イベントドリブン開始レベル決定
	//=========================================================
	event_lev = fnet->net->out[0]->level;

	for(i=1; i<fnet->net->n_out; i++){
		if(event_lev > fnet->net->out[i]->level){
			event_lev = fnet->net->out[i]->level;	//低いレベルがあったら更新
		}
	}

	//=========================================================
	// イベントドリブン実行(全経路を保証するようにFSIM)
	//=========================================================
	while(1){

		//-------------------------------------------
		// レベライズスタックから信号線を取り出す
		//-------------------------------------------
		temp_net = slev_temp[event_lev].net[slev_temp[event_lev].n_net-1];	//ケツから取り出す
		
		//-------------------------------------------
		// 計算済みフラグを代入
		//-------------------------------------------
		temp_net->flag = ed_flag;

		//-------------------------------------------
		// temp_netの故障値計算
		//-------------------------------------------
		(*sfunc_dis_ppsfp[temp_net->type])(temp_net, ed_flag);
		
		//-------------------------------------------
		// 2時刻目正常値≠故障値 (故障値伝搬)
		//-------------------------------------------
		if(temp_net->dis_nval_t2->x_buf[0] != temp_net->x_fault){
			
			//--------------------------------------------------------------------
			//temp_netが疑似外部出力(PPO)の場合
			//--------------------------------------------------------------------
			if(temp_net->ppo_flag == YES){
				
				//現在レベルのレベライズスタックの保持信号線数をデクリメント
				slev_temp[event_lev].n_net--;
				
				//故障伝搬テストパターンのチェック(正常値と故障値のEXOR演算)
				exor_ppo = temp_net->dis_nval_t2->x_buf[0] ^ temp_net->x_fault;

				//対象PPOで検出したテストパターンをチェック(※通常は故障なので注意)
				for(i=0; i<tp_count; i++){
					if( (exor_ppo & MASKbit[i])!=0 ){							//対象bitに1が立ってる(正常値0,故障値1)
						Set_NINT_One(propa_po[temp_net->ppo_id].det_flag, i);	//対象PPOで故障のi番目が検出可能
						propa_po[temp_net->ppo_id].n_det++;						//対象PPOで検出可能な故障数を更新
					}
				}
			}
			
			//--------------------------------------------------------------------
			//内部信号線の場合は出力信号線をレベライズスタックへプッシュ
			//--------------------------------------------------------------------
			else{
				TDF_EDpush(temp_net, ed_flag);		//temp_netの出力をプッシュ
				slev_temp[event_lev].n_net--;		//現在レベルのレベライズスタックの保持信号線数をデクリメント
			}
		}

		//-------------------------------------------
		// temp_netの故障値消滅⇒出力代表信号線はプッシュしない
		//-------------------------------------------
		else{
			slev_temp[event_lev].n_net--;	//現在レベルのレベライズスタックの保持信号線数をデクリメント
		}
		
		//-------------------------------------------
		// event_levを更新(現event_levのスタック内信号線保持数が0になったとき)
		//-------------------------------------------
		if(slev_temp[event_lev].n_net == 0){

			//レベライズスタック内を探索
			for(i=event_lev+1; i<=max_level; i++){
				//保持信号線数≠0のレベルスタック発見
				if(slev_temp[i].n_net != 0){
					event_lev = i;		//event_lev更新
					level_flag++;		//break阻止
					break;
				}
			}

			//レベライズスタックの中身が全部空だった
			if(level_flag == 0){
				break;	//イベントドリブン終了
			}

			//次のevent_lev更新時に備えてlevel_flagを初期化
			level_flag = 0;

		}

	}//while


}

