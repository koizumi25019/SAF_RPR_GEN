//------------------------------------------------------------------------------------
//  関数名 : TDF_2v_dis_ED_and
//  機  能 : 【AND】2値縮退故障イベントドリブン(故障値計算)
//  戻り値 : なし
//  引  数 : t_net(対象信号線), ed_flag(現在のイベントフラグ値)
//------------------------------------------------------------------------------------
void	TDF_2v_dis_ED_and(S_NLIST *t_net, unsigned int ed_flag){

	int				i;
	
	//================================================
	//入力の0番目の影響信号線値代入
	//================================================
	//-----------------------------------
	//入力が計算済み ⇒ 故障値を代入
	//-----------------------------------
	if(t_net->in[0]->flag == ed_flag){
		t_net->x_fault = t_net->in[0]->x_fault;
	}
	//-----------------------------------
	//正常値を代入
	//-----------------------------------
	else{
		t_net->x_fault = t_net->in[0]->dis_nval_t2->x_buf[0];
	}
	
	//================================================
	//残りの入力の影響信号線値計算
	//================================================
	for(i=1; i<t_net->n_in; i++){
		
		//-----------------------------------
		//入力が計算済み ⇒ 故障値で計算
		//-----------------------------------
		if(t_net->in[i]->flag == ed_flag){
			t_net->x_fault &= t_net->in[i]->x_fault;
		}

		//-----------------------------------
		//正常値で計算
		//-----------------------------------
		else{
			t_net->x_fault &= t_net->in[i]->dis_nval_t2->x_buf[0];
		}
	}
	
}

