//------------------------------------------------------------------------------------
//  関数名 : TDF_2v_dis_ED_exor
//  機  能 : 【EXOR】2値縮退故障イベントドリブン(故障値計算)
//  戻り値 : なし
//  引  数 : t_net(対象信号線), ed_flag(現在のイベントフラグ値)
//※2入力のみ対応
//------------------------------------------------------------------------------------
void	TDF_2v_dis_ED_exor(S_NLIST *t_net, unsigned int ed_flag){

	
	//------------------------------------------------
	// 2入力とも計算済み⇒両方故障値で計算
	//------------------------------------------------
	if(t_net->in[0]->flag==ed_flag && t_net->in[1]->flag==ed_flag){
		t_net->x_fault = t_net->in[0]->x_fault ^ t_net->in[1]->x_fault;
	}
	//------------------------------------------------
	// 0番目入力のみ計算済み(0番目入力のみ故障値で計算)
	//------------------------------------------------
	else if(t_net->in[0]->flag == ed_flag){
		t_net->x_fault = t_net->in[0]->x_fault ^ t_net->in[1]->dis_nval_t2->x_buf[0];
	}
	
	//------------------------------------------------
	// 1番目入力のみ計算済み(1番目入力のみ故障値で計算)
	//------------------------------------------------
	else if(t_net->in[1]->flag == ed_flag){
		t_net->x_fault = t_net->in[0]->dis_nval_t2->x_buf[0] ^ t_net->in[1]->x_fault;
	}
	
	//------------------------------------------------
	// 2入力とも正常値計算
	//------------------------------------------------
	else{
		t_net->x_fault = t_net->in[0]->dis_nval_t2->x_buf[0] ^ t_net->in[1]->dis_nval_t2->x_buf[0];
	}

}

