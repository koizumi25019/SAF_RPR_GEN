void	file_output_stil_to_txt(FILE* tp, FILE* fp){

	int		i,j;


	//==================================
	// 縮退故障の場合
	//==================================
	if(opt.fmodel == SAF){
		//read_tp_stil_saf(tp);
		n_tp_int = pi_tp[0].tp->int_num;	//unsigned int配列数保存
	}
	//==================================
	// 遷移故障の場合
	//==================================
	else if(opt.fmodel == TDF){
		//read_tp_stil_tdf(tp);
		n_tp_int = pi_tp[0].tp->int_num;	//unsigned int配列数保存
	}


	//================================================
	// 組合せ回路の場合
	//================================================
	if(n_dff == 0){
		for(i=0; i<n_tp; i++){
			for(j=0; j<n_pi; j++){
				//-------------------------------------
				// 対象PIの正常値=0
				//-------------------------------------
				if( Get_NBit(pi[j]->nval, i) == 0 ){
					fprintf(fp, "0");
				}

				//-------------------------------------
				// 対象PIの正常値=1
				//-------------------------------------
				else if( Get_NBit(pi[j]->nval, i) == 1 ){
					fprintf(fp, "1");
				}

				//-------------------------------------
				// 対象PIの正常値=X
				//-------------------------------------
				else if( Get_NBit(pi[j]->nval, i) == 3 ){
					fprintf(fp, "X");
				}
			}
			fprintf(fp, "\n");
		}
	}
	
	//================================================
	// 順序回路の場合
	//================================================
	else{
		
	}

	//ファイルクローズ
	//fclose(fp);
}