void file_output_po_pin(FILE* fp){

	int					j;

	//===========================================================
	// 【縮退故障】組合せ回路の場合 (POを出力)
	//===========================================================
	if(opt.fmodel == SAF){
		for(j=0; j<n_po; j++)fprintf(fp, "%s\n", po[j]->name);
	}

	
	//===========================================================
	// 【遷移故障】順序回路の場合 (※2時刻目PPOのみ出力)
	//===========================================================
	else if(opt.fmodel == TDF){
		for(j=0; j<n_ppi; j++)fprintf(fp, "%s\n", s_nl[ppi_tp[j].nl_id].in[0]->name);
	}
}