//--------------------------------------------------
//  関数名 : mem_alloc
//  機  能 : メモリアロケーション
//  戻り値 : アロケーションした領域の先頭アドレス
//  引  数 :
//    num  : 配列の要素数
//    size : 要素1つ当たりのバイト数
//--------------------------------------------------
void  *mem_alloc (int  num,	int  size)
{
  void  *p;       
  
  if ((p = (void *)malloc(num * size)) == NULL) {
	fprintf(stderr,"Memory allocation error\n");
	exit( 1 );
  }
  
  return( p );

}
