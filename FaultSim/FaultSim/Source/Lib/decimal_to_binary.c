//--------------------------------------------------------------------
//関数名：dtob
//機能　：10進数を2進数で表示
//引数　：x(2進数表示させたいunsigned int型の変数), bit_len(xの有効ビット長[1〜32])
//戻り値：なし
//--------------------------------------------------------------------
void dtob(unsigned int x, int bit_len){

	int bit = 1, i;
	char c[32];

	//===================================
	// 2進数に変換
	//===================================
	for (i = 0; i<bit_len; i++) {
		if (x & bit){
			c[i] = '1';
		}
		else{
			c[i] = '0';
		}

		bit <<= 1;
	}
	
	//===================================
	// 2進数で表示
	//===================================
	for (i=bit_len-1; i>=0; i--) {
		putchar(c[i]);
	}

	printf("\n");

}