//機能　：X抽出後テスト集合に対するテスト圧縮(Dsatur)の実行
//引数　：ファイル名ポインタ
//戻り値：なし
//----------------------------------------------
int run_dsatur(char** file_names){
	
	char	cmd[1000];
	int		n_tp;

	printf("\n//=======================================================\n");
	printf("// X抽出後テスト集合にDsatur実行\n");
	printf("//=======================================================\n");


	//=========================================================
	// Dsatur実行コマンドの作成
	//=========================================================
	strcpy(cmd, "Dsatur.exe ");
	strcat(cmd, file_names[F_XTXT]);
	

	//=========================================================
	// Dsatur実行
	//=========================================================
	n_tp = system(cmd);
	printf("\n");


	return n_tp;
}